"""Starter for Lab 06: Fine-tune with LoRA.

Run this file once, unmodified, to confirm your environment works:

    python lab06_starter.py

It downloads a small pretrained language model and a small dataset, measures
the zero-shot accuracy, then trains a LoRA adapter for a few steps.

How classification works here. The model is a decoder-only language model.
Every example becomes a prompt that ends in a cue, for example
"Text: i didnt feel humiliated\\nEmotion:", and the answer is ONE token, the
first token of the label word, for example " sadness". To classify, we run the
prompt and compare the model's scores for the label tokens only. No new output
layer is added, so the same scoring works before and after training.

Do not edit this file directly. Copy it into your repository and import from
it, or copy what you need into your own work.
"""
import random
import time

import torch
import torch.nn as nn
from datasets import load_dataset
from transformers import AutoModelForCausalLM, AutoTokenizer

MODEL_NAME = "HuggingFaceTB/SmolLM2-135M"
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

TASKS = {
    "emotion": dict(hub="dair-ai/emotion", text="text", label="label",
                    words=["sadness", "joy", "love", "anger", "fear", "surprise"],
                    prompt="Text: {text}\nEmotion:"),
    "ag_news": dict(hub="fancyzhx/ag_news", text="text", label="label",
                    words=["World", "Sports", "Business", "Technology"],
                    prompt="Article: {text}\nTopic:"),
}


# ---------------------------------------------------------------- data

def load_task(task="emotion", n_train=600, n_test=500, data_seed=0, max_text_tokens=32, tokenizer=None,
              eval_split="test"):
    """Return (train, test, label_token_ids). Each example is a dict with
    prompt_ids (list of ints), answer_id (int, the label token) and label (int).

    The data sample depends only on data_seed, so every run and every student
    using the same arguments gets the same examples.
    """
    cfg = TASKS[task]
    tok = tokenizer or AutoTokenizer.from_pretrained(MODEL_NAME)
    raw = load_dataset(cfg["hub"])
    train_raw = raw["train"].shuffle(seed=data_seed).select(range(n_train))
    test_raw = raw[eval_split].shuffle(seed=data_seed).select(range(n_test))

    label_ids = [tok.encode(" " + w)[0] for w in cfg["words"]]
    assert len(set(label_ids)) == len(label_ids), "label words must start with different tokens"

    def encode(row):
        text_ids = tok.encode(row[cfg["text"]])[:max_text_tokens]
        prompt = cfg["prompt"].format(text=tok.decode(text_ids).strip())
        return dict(prompt_ids=tok.encode(prompt), answer_id=label_ids[row[cfg["label"]]], label=row[cfg["label"]])

    return [encode(r) for r in train_raw], [encode(r) for r in test_raw], label_ids


def pad_batch(examples, pad_id):
    """Right-pad prompt plus answer into tensors.

    Returns input_ids, attention_mask and prompt_lens, each of shape (batch, ...).
    The sequence for one example is prompt_ids followed by the single answer token.
    """
    seqs = [e["prompt_ids"] + [e["answer_id"]] for e in examples]
    width = max(len(s) for s in seqs)
    input_ids = torch.full((len(seqs), width), pad_id, dtype=torch.long)
    attention_mask = torch.zeros((len(seqs), width), dtype=torch.long)
    for i, s in enumerate(seqs):
        input_ids[i, :len(s)] = torch.tensor(s)
        attention_mask[i, :len(s)] = 1
    prompt_lens = torch.tensor([len(e["prompt_ids"]) for e in examples])
    return input_ids, attention_mask, prompt_lens


def all_tokens_labels(input_ids, attention_mask, prompt_lens):
    """Default loss mask: score EVERY real token, prompt and answer alike.

    Returns labels with the same shape as input_ids. A value of -100 means
    'do not score this position'. You will write answer_only_labels with the
    same signature and compare the two.
    """
    labels = input_ids.clone()
    labels[attention_mask == 0] = -100
    return labels


# ---------------------------------------------------------------- model

def load_model():
    """Load the pretrained model and tokenizer in 32-bit precision."""
    tok = AutoTokenizer.from_pretrained(MODEL_NAME)
    tok.pad_token = tok.eos_token
    model = AutoModelForCausalLM.from_pretrained(MODEL_NAME, dtype=torch.float32).to(DEVICE)
    return model, tok


def apply_lora(model, r, alpha=None, target_modules=("q_proj", "v_proj")):
    """Wrap the model with peft's LoRA. alpha defaults to 2 * r. Returns the wrapped model."""
    from peft import LoraConfig, get_peft_model
    cfg = LoraConfig(r=r, lora_alpha=alpha if alpha is not None else 2 * r, target_modules=list(target_modules),
                     lora_dropout=0.0, bias="none", task_type="CAUSAL_LM")
    return get_peft_model(model, cfg)


def count_params(model):
    """Return (trainable, total) parameter counts."""
    total = sum(p.numel() for p in model.parameters())
    trainable = sum(p.numel() for p in model.parameters() if p.requires_grad)
    return trainable, total


def tensor_bytes(t):
    return t.numel() * t.element_size()


def training_state_bytes(model, optimizer):
    """Bytes held for weights, gradients and optimizer state (activations excluded)."""
    w = sum(tensor_bytes(p) for p in model.parameters())
    g = sum(tensor_bytes(p.grad) for p in model.parameters() if p.grad is not None)
    s = sum(tensor_bytes(t) for st in optimizer.state.values() for t in st.values() if torch.is_tensor(t) and t.dim() > 0)
    return w, g, s


# ---------------------------------------------------------------- training and evaluation

@torch.no_grad()
def evaluate(model, tok, test, label_ids, batch_size=32):
    """Accuracy of the label-token scoring on the test examples. Chance is 1 / number of labels."""
    model.eval()
    ids = torch.tensor(label_ids, device=DEVICE)
    correct = 0
    for i in range(0, len(test), batch_size):
        chunk = test[i:i + batch_size]
        prompts = [dict(prompt_ids=e["prompt_ids"], answer_id=e["answer_id"]) for e in chunk]
        input_ids, mask, plens = pad_batch(prompts, tok.pad_token_id)
        logits = model(input_ids=input_ids.to(DEVICE), attention_mask=mask.to(DEVICE)).logits
        last = logits[torch.arange(len(chunk)), (plens - 1).to(DEVICE)]          # scores at the last prompt position
        pred = last[:, ids].argmax(dim=-1).cpu()
        correct += (pred == torch.tensor([e["label"] for e in chunk])).sum().item()
    return correct / len(test)


def train(model, tok, train_examples, steps=120, lr=1e-4, batch_size=8, seed=0, labels_fn=all_tokens_labels,
          warmup=10):
    """Train the parameters that require gradients with AdamW. Returns a dict of measurements."""
    params = [p for p in model.parameters() if p.requires_grad]
    opt = torch.optim.AdamW(params, lr=lr, weight_decay=0.0)
    rng = random.Random(seed)
    if DEVICE == "cuda":
        torch.cuda.reset_peak_memory_stats()
    model.train()
    losses, start = [], time.time()
    for step in range(1, steps + 1):
        for g in opt.param_groups:
            g["lr"] = lr * min(1.0, step / warmup)
        batch = rng.sample(train_examples, batch_size)
        input_ids, mask, plens = pad_batch(batch, tok.pad_token_id)
        labels = labels_fn(input_ids, mask, plens)
        out = model(input_ids=input_ids.to(DEVICE), attention_mask=mask.to(DEVICE), labels=labels.to(DEVICE))
        opt.zero_grad(set_to_none=True)
        out.loss.backward()
        torch.nn.utils.clip_grad_norm_(params, 1.0)
        opt.step()
        losses.append(out.loss.item())
    seconds = time.time() - start
    w, g, s = training_state_bytes(model, opt)
    trainable, total = count_params(model)
    return dict(first_loss=sum(losses[:5]) / 5, last_loss=sum(losses[-5:]) / 5, seconds=seconds,
                seconds_per_step=seconds / steps, trainable=trainable, total=total,
                weight_bytes=w, grad_bytes=g, optimizer_bytes=s,
                peak_cuda_bytes=torch.cuda.max_memory_allocated() if DEVICE == "cuda" else None)


def run(mode, seed, train_examples, test, label_ids, r=8, steps=120, lr=None, labels_fn=all_tokens_labels,
        batch_size=8):
    """One complete run on a freshly loaded model. mode is 'none' (zero-shot), 'full' or 'lora'.

    Returns a dict with the accuracy and the measurements from train().
    """
    torch.manual_seed(seed)
    model, tok = load_model()
    if mode == "lora":
        model = apply_lora(model, r)
    if mode == "none":
        trainable, total = count_params(model)
        return dict(accuracy=evaluate(model, tok, test, label_ids), trainable=0, total=total)
    lr = lr if lr is not None else (5e-5 if mode == "full" else 1e-3)
    info = train(model, tok, train_examples, steps=steps, lr=lr, batch_size=batch_size, seed=seed, labels_fn=labels_fn)
    info["accuracy"] = evaluate(model, tok, test, label_ids)
    return info


if __name__ == "__main__":
    print("device:", DEVICE)
    model, tok = load_model()
    train_ex, test_ex, label_ids = load_task("emotion", n_train=200, n_test=100)
    print("example prompt:", repr(tok.decode(train_ex[0]["prompt_ids"])), "answer:", repr(tok.decode([train_ex[0]["answer_id"]])))
    print("zero-shot accuracy (chance 0.167):", round(evaluate(model, tok, test_ex, label_ids), 3))
    info = run("lora", 0, train_ex, test_ex, label_ids, r=8, steps=30)
    print(f"LoRA r=8, 30 steps: accuracy {info['accuracy']:.3f}, trainable {info['trainable']:,} of {info['total']:,}, "
          f"{info['seconds_per_step']:.2f} s/step")
